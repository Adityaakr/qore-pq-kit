/**
 * vectors.ts - write vectors/threshold.json, the cross-language test vectors
 * for the threshold module. Deterministic: every random value comes from a
 * keccak counter, so running it again gives the same file, and
 * `test-ts/threshold.test.ts` fails if the committed file has drifted.
 *
 *   npm run vectors
 *
 * `test/threshold/ThresholdVectors.t.sol` reads the file and checks Shamir.sol
 * and SealedSlot.sol against every value in it, byte for byte.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { encodeAbiParameters, keccak256, type Address, type Hex } from "viem";
import {
  DEM_DOMAIN,
  FIELD_P,
  KEY_DOMAIN,
  SHARE_DOMAIN,
  combine,
  keyHash,
  keystream,
  shareHash,
  split,
  xorSlot,
  type Share,
  type SlotBinding,
} from "./threshold.ts";

const hex32 = (v: bigint): Hex => `0x${v.toString(16).padStart(64, "0")}`;

/** A deterministic stream of field elements: keccak(label, counter), top bit cleared, below P. */
export function seededField(label: string): () => bigint {
  let counter = 0n;
  return () => {
    for (;;) {
      const h = BigInt(keccak256(encodeAbiParameters([{ type: "string" }, { type: "uint256" }], [label, counter++])));
      const v = h & ((1n << 255n) - 1n);
      if (v < FIELD_P) return v;
    }
  };
}

interface CaseSpec {
  name: string;
  chainId: bigint;
  seq: bigint;
  t: number;
  n: number;
  key?: bigint;
}

const APP = "0x1111111111111111111111111111111111111111" as Address;
const SENDER = "0x2222222222222222222222222222222222222222" as Address;

const SPECS: CaseSpec[] = [
  { name: "2-of-3 on qorechain-diana", chainId: 9800n, seq: 0n, t: 2, n: 3 },
  { name: "2-of-3, next seq", chainId: 9800n, seq: 1n, t: 2, n: 3 },
  { name: "3-of-5", chainId: 9800n, seq: 7n, t: 3, n: 5 },
  { name: "1-of-1 (share is the key)", chainId: 9800n, seq: 2n, t: 1, n: 1 },
  { name: "7-of-7", chainId: 9800n, seq: 3n, t: 7, n: 7 },
  { name: "key P - 1", chainId: 9800n, seq: 4n, t: 2, n: 3, key: FIELD_P - 1n },
  { name: "key 0", chainId: 9800n, seq: 5n, t: 2, n: 3, key: 0n },
  { name: "2-of-3 on another chain", chainId: 31337n, seq: 0n, t: 2, n: 3 },
];

/** Every t-element subset of 1..n, in lexicographic order (n is small). */
function subsets(n: number, t: number): number[][] {
  const out: number[][] = [];
  const pick = (start: number, acc: number[]) => {
    if (acc.length === t) return void out.push([...acc]);
    for (let i = start; i <= n; i++) pick(i + 1, [...acc, i]);
  };
  pick(1, []);
  return out;
}

export function buildVectors() {
  const cases = SPECS.map((s) => {
    const random = seededField(`qore-pq-kit/threshold/${s.name}`);
    const key = s.key ?? random();
    const shares = split(key, s.t, s.n, random);
    const b: SlotBinding = { chainId: s.chainId, app: APP, sender: SENDER, seq: s.seq };
    const plaintext = hex32(random());
    const ct = xorSlot(b, key, plaintext);
    const byIndex = new Map(shares.map((sh) => [sh.index, sh] as const));
    const opening = subsets(s.n, s.t).slice(0, 10);
    for (const set of opening) {
      if (combine(set.map((i) => byIndex.get(i)!)) !== key) throw new Error(`${s.name}: subset ${set} does not recombine`);
    }
    // t - 1 shares must NOT give the key (always true for a random dealing, checked anyway).
    const short = s.t > 1 ? shares.slice(0, s.t - 1) : [];
    const shortValue = short.length > 0 ? combine(short as Share[]) : 0n;
    if (short.length > 0 && shortValue === key) throw new Error(`${s.name}: t - 1 shares gave the key`);
    return {
      name: s.name,
      chainId: hex32(s.chainId),
      app: APP,
      sender: SENDER,
      seq: hex32(s.seq),
      t: s.t,
      n: s.n,
      key: hex32(key),
      plaintext,
      keystream: keystream(b, key),
      ct,
      keyHash: keyHash(b, key),
      shares: shares.map((sh) => hex32(sh.value)),
      shareHashes: shares.map((sh) => shareHash(b, sh.index, sh.value)),
      openingSets: opening,
      shortSet: short.map((sh) => sh.index),
      shortValue: hex32(shortValue),
    };
  });
  return {
    description:
      "Cross-language vectors for qore-pq-kit threshold (Shamir.sol, SealedSlot.sol, scripts/threshold.ts). Generated by `npm run vectors`; do not edit by hand.",
    fieldP: hex32(FIELD_P),
    domains: {
      key: KEY_DOMAIN,
      share: SHARE_DOMAIN,
      dem: DEM_DOMAIN,
      keyLabel: "qore-pq-kit.SealedSlot.key.v1",
      shareLabel: "qore-pq-kit.SealedSlot.share.v1",
      demLabel: "qore-pq-kit.SealedSlot.dem.v1",
    },
    count: cases.length,
    cases,
  };
}

export const VECTORS_PATH = join(dirname(fileURLToPath(import.meta.url)), "..", "vectors", "threshold.json");

export function vectorsText(): string {
  return JSON.stringify(buildVectors(), null, 2) + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(VECTORS_PATH, vectorsText());
  console.log(`wrote ${VECTORS_PATH}`);
}

